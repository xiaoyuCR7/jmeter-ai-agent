def has_chinese(value: Any) -> bool:
    return isinstance(value, str) and bool(_CJK.search(value))


def localize(value: Any, lang: str) -> Any:
    """A copy of registry data with its labels, descriptions and examples in English when ``lang`` is 'en'."""
    if lang != 'en':
        return value

    def walk(node: Any, key: Any = None) -> Any:
        if isinstance(node, dict):
            return {name: walk(item, name) for name, item in node.items()}
        if isinstance(node, list):
            return [walk(item, key) for item in node]
        if key in TRANSLATED_KEYS and isinstance(node, str):
            return EN.get(node, node)
        return node
    return walk(value)
